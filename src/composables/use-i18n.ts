const STORAGE_KEY = 'market-research-locale'
const isBrowser = typeof window !== 'undefined'
const localeStore = ref<Locale>('zh')

const toLocale = (value: string | null): Locale => (value === 'en' || value === 'zh' ? value : 'zh')

if (isBrowser) {
  localeStore.value = toLocale(window.localStorage.getItem(STORAGE_KEY))
  document.documentElement.lang = localeStore.value === 'en' ? 'en' : 'zh-CN'
}

const setLocale = (value: Locale) => {
  localeStore.value = value === 'en' ? 'en' : 'zh'
  if (isBrowser) {
    window.localStorage.setItem(STORAGE_KEY, localeStore.value)
    document.documentElement.lang = localeStore.value === 'en' ? 'en' : 'zh-CN'
  }
}

const t = (key: string, params: Record<string, string | number> = {}) => {
  const resolve = (source: DictionaryNode, segments: string[]) => {
    let node: string | DictionaryNode | undefined = source
    for (const segment of segments) {
      if (node && typeof node === 'object' && segment in node) node = node[segment]
      else return undefined
    }
    return node
  }

  const found =
    (resolve(messages[localeStore.value], key.split('.')) as string | undefined) ??
    (resolve(messages.zh, key.split('.')) as string | undefined)
  const template = typeof found === 'string' ? found : key

  return Object.entries(params).reduce(
    (current, [name, value]) => current.split(`{${name}}`).join(String(value)),
    template,
  )
}

const useI18n = () => ({ locale: localeStore, t, setLocale })

export { useI18n }
